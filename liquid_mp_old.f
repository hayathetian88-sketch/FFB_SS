      SUBROUTINE LIQUID_MP(MCOLOR,MCPART,NCOLOR,NCPART,LLOOP,
     *                  N,N1,N2,ME,MELM,NE,NP,NEX,NODE,NUMIP,
     *                  ICAVI,ISOLT,NS,NL,ITIME,JSET,NMAX,
     *                  NCRS,NCRS2,NPPMAX,ITPCRS,IUT6,IUT0,JUNROL,
     *                  NPP,IPCRS,LTAB,NITR,RES,
     *                  EPS,EPSRE,SIGMA,CGAS,CLQD,
     *                  FLINLT,FLIMIT,FLMIN,
     *                  CEB,CUPWD,CVISL,
     *                  E,EX,EY,EZ,EXX,EYY,EZZ,EXY,EYZ,EXZ,
     *                  SN,DELTA,CM,
     *                  UG,VG,WG,P,DT,VISC,SCT,F,FESRC,FE,
     *                  F3,F2,F1,F0,
     *                  CAVRAD,CJS,CALPHA,
     *                  NPINLT,LPINLT,
     *                  F3INLT,F2INLT,F1INLT,F0INLT,
     *                  NPSET, LPSET1,LPSET2,LPSET3,
     *                  COVER1,COVER2,COVER3,
     *                  NPSND ,LPSND ,NPTSND,IPSET,IPSRC,
     *                  NPRCV ,LPRCV ,NPTRCV,
     *                  IPART,LDOM,NBPDOM,NDOM,IPSLF,IPSND,MBPDOM,
     *                  LFIX3D,LPFIX,RX,RY,ACRS,A,
     *                  WRK01,WRK02,WRK03,
     *					WRK04,WRK05,WRK06,
     *					WRK07,F3X,F3Y,
     *					F2X,F2Y,F1X,
     *					F1Y,F0X,F0Y,
     *					RHS,A0,TS,
     *					TACRS,IERR)

      IMPLICIT NONE
C
C[INPUT]
      INTEGER*4 MCOLOR,MCPART,
     *          NCOLOR(4),NCPART(MCOLOR,4),LLOOP(MCPART,MCOLOR,4),
     *          N,N1,N2,ME,MELM,NE,NP,NEX(12),NODE(N2,NE),NUMIP(NP),
     *          ICAVI,ISOLT,NS,NL,ITIME,JSET,NMAX,
     *          NCRS,NPP(NP),IPCRS(NCRS),LTAB(N1,N2,NE),
     *          NPPMAX,NCRS2,ITPCRS(NCRS2),IUT6,IUT0,JUNROL
      REAL*4    EPS,EPSRE,SIGMA,CGAS,CLQD,FLINLT,FLIMIT,FLMIN,
     *          CAVRAD,CJS,CALPHA,F3INLT,F2INLT,F1INLT,F0INLT
      REAL*4    UG(NE),VG(NE),WG(NE),P(NE),DT,VISC(NE),SCT
      REAL*4    E(MELM),EX(MELM),EY(MELM),EZ(MELM),
     *          EXX(MELM),EYY(MELM),EZZ(MELM),
     *          EXY(MELM),EYZ(MELM),EXZ(MELM),
     *          SN(N1,NE),DELTA(NE),CM(NP)
      INTEGER*4 NPINLT,LPINLT(NPINLT)
      INTEGER*4 IPART,NDOM,MBPDOM,
     *          LDOM(NDOM),NBPDOM(NDOM),
     *          IPSLF(MBPDOM,NDOM),IPSND(MBPDOM,NDOM)
      INTEGER*4 NPSND,NPRCV
      INTEGER*4 NPSET,LPSET1(NPSET),LPSET2(NPSET),LPSET3(NPSET),
     *          LPSND (NDOM),NPTSND(NDOM) ,LPRCV (NDOM) ,NPTRCV(NDOM),
     *          IPSET (MBPDOM,NDOM),IPSRC (MBPDOM,NDOM)
      REAL*4    COVER1(NPSET),COVER2(NPSET),COVER3(NPSET)
C
C[INPUT/OUTPUT]
      REAL*4    F(NP),F3(NP),F2(NP),F1(NP),F0(NP)
C
C[OUTPUT]
      INTEGER*4 IERR,NITR
      REAL*4    FESRC(NE),FE(NE)
      REAL*4    RES
C
C[WORK]
      INTEGER*4 LFIX3D(NP),LPFIX(NP)
      REAL*4    RX(0:N,ME),RY(0:N,ME),ACRS(NCRS),A(N1,N2,NE),
     *          WRK01(NP),WRK02(NP),WRK03(NP),WRK04(NP),
     *          WRK05(NP),WRK06(NP),WRK07(NP),
     *          RHS(NP),A0(NP),TS(0:NP),TACRS(NCRS2),
     *          F3Y(NP),F2Y(NP),F1Y(NP),F0Y(NP),
     *          F3X(NP),F2X(NP),F1X(NP),F0X(NP),PN(NP)
C
C[LOCAL]
      INTEGER*4 MAXBUF,IDUM,I,IE,IP,IB,ISEND,IDIM,NB,NPFIX
      INTEGER*4 IP1,IP2,IP3,IP4,IP5,IP6,IP7,IP8
      REAL*4    COEF,CEB,CUPWD,CVISL,RESR,SOURCE,DELTAP,
     *          CALPHA0,CALPHA1,FY,CAV3,AVERAD,EVPCND,FVX,
     *          PIRQ3,F3LIMIT,F3MAX,MAXH0
C
      INTEGER*4 IBCGS,NPMIN
      DATA IBCGS  / 0 /
C
      CHARACTER*60 ERMSGC
     & / ' ## SUBROUTINE LIQUID: FATAL      ERROR REPORT   ; RETURNED' /
C 
      INTEGER*4 ICRS,K
C
      IERR=0
C
      MAXBUF = ME*(N2+1)
C
C       WRITE(IUT6,*) 'DEBUG MP 1'
C
      IF(ITIME.EQ.0) THEN
      	MAXH0 = 0
        DO IP = 1 , NP
          F3(IP) = 3.12E-2
          F2(IP) = 1.56E2
          F1(IP) = 7.8E5
          F0(IP) = 3.9E9
        END DO
C
C		 	MAXH0 = 0
C		 	NPMIN = 0
C       DO IE = 1 , NE
C        MAXH0 =  P(IE) - MAXH0
C		  IF(MAXH0.LT.0)THEN 
C		  MAXH0 = P(IE)
C		  NPMIN = IE
C		  ELSE
C		  MAXH0 = P(IE)- MAXH0 
C		  ENDIF
C		END DO
C     WRITE(IUT6,*) ' MIN OF P =',MAXH0
C      WRITE(IUT6,*) ' NODE AT P-MIN =',NPMIN
C
       GOTO 4000
      ENDIF

CCYY [0] PREPARE FIX B.C. LIST
C
      DO 1100 IP = 1 , NP
          LFIX3D(IP) = 0
          LPFIX(IP) = 0
 1100 CONTINUE
C
      DO 1110 IB = 1 , NPINLT
          LFIX3D(LPINLT(IB))=1
 1110 CONTINUE
C
      DO 1120 IB = 1 , NPSET
          ISEND = LPSET3(IB)
          IF(ISEND.GT.0) GO TO 1120
          LFIX3D(LPSET1(IB))=1
 1120 CONTINUE
C
      NPFIX=0
      DO 1200 IP = 1 , NP
          IF(LFIX3D(IP).EQ.0) GO TO 1200
          NPFIX=NPFIX+1
          LPFIX(NPFIX) = IP
 1200 CONTINUE
C
      IERR=0
C
C
C		 	MAXH0 = 0
C		 	NPMIN = 0
C       DO IE = 1 , NE
C        MAXH0 =  P(IE) - MAXH0
C		  IF(MAXH0.LT.0)THEN 
C		  MAXH0 = P(IE)
C		  NPMIN = IE
C		  ELSE
C		  MAXH0 = P(IE)- MAXH0
C		  ENDIF
C		END DO
C      WRITE(IUT6,*) ' MIN OF P =',MAXH0
C      WRITE(IUT6,*) ' NODE AT P-MIN =',NPMIN
C
C
C       WRITE(IUT6,*) 'DEBUG MP 2'
C
CCYY [1] DEFINE PARAMETERS
      PIRQ3   = 4.1887902E0
      CALPHA0 = CJS*CAVRAD/3.E0
      CALPHA1 = CALPHA0*CAVRAD
      MAXH0 = 0

      DO 2000 IE = 1 , NE
          IP1=NODE(1,IE)
          IP2=NODE(2,IE)
          IP3=NODE(3,IE)
          IP4=NODE(4,IE)
          IP5=NODE(5,IE)
          IP6=NODE(6,IE)
          IP7=NODE(7,IE)
          IP8=NODE(8,IE)

		IF(IP8.NE.0) THEN 
              F3Y(IE) = ( F3(IP1)+F3(IP2)+F3(IP3)+F3(IP4)
     *                  +F3(IP5)+F3(IP6)+F3(IP7)+F3(IP8))/8.0E0
              F2Y(IE) = ( F2(IP1)+F2(IP2)+F2(IP3)+F2(IP4)
     *                  +F2(IP5)+F2(IP6)+F2(IP7)+F2(IP8))/8.0E0
              F1Y(IE) = ( F1(IP1)+F1(IP2)+F1(IP3)+F1(IP4)
     *                  +F1(IP5)+F1(IP6)+F1(IP7)+F1(IP8))/8.0E0
              F0Y(IE) = ( F0(IP1)+F0(IP2)+F0(IP3)+F0(IP4)
     *                  +F0(IP5)+F0(IP6)+F0(IP7)+F0(IP8))/8.0E0
		ELSE IF(IP6.NE.0) THEN
              F3Y(IE) = ( F3(IP1)+F3(IP2)+F3(IP3)+F3(IP4)
     *                  +F3(IP5)+F3(IP6))/6.0E0
              F2Y(IE) = ( F2(IP1)+F2(IP2)+F2(IP3)+F2(IP4)
     *                  +F2(IP5)+F2(IP6))/6.0E0
              F1Y(IE) = ( F1(IP1)+F1(IP2)+F1(IP3)+F1(IP4)
     *                  +F1(IP5)+F1(IP6))/6.0E0
              F0Y(IE) = ( F0(IP1)+F0(IP2)+F0(IP3)+F0(IP4)
     *                  +F0(IP5)+F0(IP6))/6.0E0
		ELSE IF(IP5.NE.0) THEN
              F3Y(IE) = ( F3(IP1)+F3(IP2)+F3(IP3)+F3(IP4)
     *                  +F3(IP5))/5.0E0
              F2Y(IE) = ( F2(IP1)+F2(IP2)+F2(IP3)+F2(IP4)
     *                  +F2(IP5))/5.0E0
              F1Y(IE) = ( F1(IP1)+F1(IP2)+F1(IP3)+F1(IP4)
     *                  +F1(IP5))/5.0E0
              F0Y(IE) = ( F0(IP1)+F0(IP2)+F0(IP3)+F0(IP4)
     *                  +F0(IP5))/5.0E0
		ELSE IF(IP4.NE.0) THEN
              F3Y(IE) = ( F3(IP1)+F3(IP2)+F3(IP3)+F3(IP4))/4.0E0
              F2Y(IE) = ( F2(IP1)+F2(IP2)+F2(IP3)+F2(IP4))/4.0E0
              F1Y(IE) = ( F1(IP1)+F1(IP2)+F1(IP3)+F1(IP4))/4.0E0
              F0Y(IE) = ( F0(IP1)+F0(IP2)+F0(IP3)+F0(IP4))/4.0E0
		ENDIF
C
C
C
		FY = 1.E0-PIRQ3*F3Y(IE)
C
C
		CAV3 = (CGAS-(CGAS-CLQD)*FY)*(P(IE)+0.5E0*SIGMA)
		CAV3 = CAV3/((CALPHA+FY-FY*FY)*3.E0)
C
C
		AVERAD = (CALPHA1*FY+F1Y(IE))/(CALPHA0*FY+F0Y(IE))
C
C
C
		SOURCE = -CJS*CAVRAD*CAV3 
C
C        MAXH0 =  SOURCE - MAXH0
C        IF(MAXH0.GT.0)THEN 
C		  MAXH0 = SOURCE
C		  ELSE
C		  MAXH0 = SOURCE - MAXH0
C		  ENDIF
C
		EVPCND = -AVERAD*CAV3
C
C
C    PER UNIT VOLUME OF LIQUID
C
C
		F0X(IE) = FY*SOURCE
C
		SOURCE  = SOURCE*CAVRAD
		F1X(IE) = FY*SOURCE+EVPCND*F0Y(IE)
C
		SOURCE  = SOURCE*CAVRAD
		F2X(IE) = FY*SOURCE+2.E0*EVPCND*F1Y(IE)
C
		SOURCE  = SOURCE*CAVRAD
		F3X(IE) = FY*SOURCE +3.E0*EVPCND*F2Y(IE)
C
C
C
          FVX = PIRQ3*F3X(IE)
          F3X(IE) = F3X(IE)*FY
          F2X(IE) = F2X(IE)-F2Y(IE)*FVX
          F1X(IE) = F1X(IE)-F1Y(IE)*FVX
          F0X(IE) = F0X(IE)-F0Y(IE)*FVX
C
C          VISC(IE) = VISC0(IE)*RHO0/RHOBUF

 2000 CONTINUE
C
C       WRITE(IUT6,*) 'DEBUG MP 3'
C

C	  MAXH0 = F0X(NPMIN)
C       WRITE(IUT6,*) ' F0X AT ELEMENT P-MIN =',MAXH0	
C      MAXH0 = F1X(NPMIN)
C       WRITE(IUT6,*) ' F1X AT ELEMENT P-MIN =',MAXH0
C      MAXH0 = F2X(NPMIN)
C       WRITE(IUT6,*) ' F2X AT ELEMENT P-MIN =',MAXH0
C      MAXH0 = F3X(NPMIN)
C       WRITE(IUT6,*) ' F3X AT ELEMENT P-MIN =',MAXH0  
C
C      WRITE(IUT6,*) ' MIN OF SOURCE =',MAXH0
C		 	MAXH0 = 0
C       DO IP = 1 , NP
C        MAXH0 =  F3X(IP) - MAXH0
C		  IF(MAXH0.GT.0)THEN 
C		  MAXH0 = F3X(IP)
C		  ELSE
C		  MAXH0 = F3X(IP) - MAXH0
C		  ENDIF
C		END DO
C      WRITE(IUT6,*) ' MAX OF F3X =',MAXH0
C
C		 	MAXH0 = 0
C       DO IP = 1 , NP
C        MAXH0 =  F0X(IP) - MAXH0
C		  IF(MAXH0.GT.0)THEN 
C		  MAXH0 = F0X(IP)
C		  ELSE
C		  MAXH0 = F0X(IP) - MAXH0
C		  ENDIF
C		END DO
C       WRITE(IUT6,*) ' MAX OF F0X =',MAXH0
C
      CALL NODLEX(NODE,ME,NP,NE,NP,N1,N2,NEX,SN,
     *            IPART,LDOM,NBPDOM,NDOM,IPSLF,IPSND,MBPDOM,
     *            F3X,F3Y,CM,IUT0,IERR,RX,RY,MAXBUF)
      CALL NODLEX(NODE,ME,NP,NE,NP,N1,N2,NEX,SN,
     *            IPART,LDOM,NBPDOM,NDOM,IPSLF,IPSND,MBPDOM,
     *            F2X,F2Y,CM,IUT0,IERR,RX,RY,MAXBUF)
      CALL NODLEX(NODE,ME,NP,NE,NP,N1,N2,NEX,SN,
     *            IPART,LDOM,NBPDOM,NDOM,IPSLF,IPSND,MBPDOM,
     *            F1X,F1Y,CM,IUT0,IERR,RX,RY,MAXBUF)
      CALL NODLEX(NODE,ME,NP,NE,NP,N1,N2,NEX,SN,
     *            IPART,LDOM,NBPDOM,NDOM,IPSLF,IPSND,MBPDOM,
     *            F0X,F0Y,CM,IUT0,IERR,RX,RY,MAXBUF)
C
      IF(IERR.NE.0) THEN
          WRITE(IUT0,*)
          WRITE(IUT0,*) ERMSGC
          RETURN
      ENDIF
C
C       WRITE(IUT6,*) 'DEBUG MP 4'
C

C
C
CCCCC SOLUTION FOR F3 CCCCCCCCCCCCCCCCCCCCC
CCYY [2] CAL. TIME, ADV., AND DIFF. TERM 
C
      CALL ADVDFL_OLD
     * (MCOLOR,MCPART,NCOLOR,NCPART,LLOOP,
     *  N1,N2,NE,NP,MELM,NEX,NODE,
     *  UG,VG,WG,DT,SCT,VISC,
     *  CGAS,CLQD,P,SIGMA,SN,
     *  CEB,CUPWD,CVISL,ICAVI,
     *  E,EX,EY,EZ,EXX,EYY,EZZ,EXY,EYZ,EXZ,
     *  A,F3,RHS,A0,
     *  DELTA,IERR)
      IDUM = 2
      CALL DDCOMX(IPART,IDUM,LDOM,NBPDOM,NDOM,IPSLF,IPSND,MBPDOM,
     *            RHS,A0,RHS,NP,IUT0,IERR,RX,RY,MAXBUF)
      IF(IERR.NE.0) THEN
          WRITE(IUT0,*)
          WRITE(IUT0,*) ERMSGC
          RETURN
      ENDIF
C
C
C
CCYY [3] ADD SOURCE TERM
C
C
      DO 2100 IP = 1,NP
          RHS(IP)=RHS(IP) + DT*F3Y(IP)/CM(IP)
 2100 CONTINUE
C
CCYY [4] MATIRIX CONVET FROM ELEMENT-WIZE TO CRS
C
      CALL E2PMAT(MCOLOR,MCPART,NCOLOR,NCPART,LLOOP,
     *            N2,N1,NE,NEX,NCRS,A,ACRS,LTAB,IUT0,IERR)
      IF(IERR.NE.0) THEN
          WRITE(IUT0,*)'ERROR CODE REPORTED FROM E2PMAT'
          WRITE(IUT0,*)ERMSGC
          RETURN
      ENDIF
C
CCYY [5] DIAGONAL SCALING
C
      CALL DGNSCL(ACRS,A0,NP,NE,NCRS,IPCRS,NPP,ME)
C
      DO 2200 IP=1, NP
          RHS(IP) = RHS(IP)/A0(IP)
 2200 CONTINUE
C
CCYY [6] CLEAR CRS MATRIX FOR DIRICHLET B.C.
C
      CALL CLRCRS(IPART,ACRS,NP,NCRS,IPCRS,NPP,
     *            A0,LFIX3D,NUMIP,WRK01)
C
CCYY [7] SET B.C. (1)INLET, (2)OVERSET
C
      IF (JSET.GE.1) THEN
          CALL OVRST1(IPART,NPSET,N1,ME,NE,NP,NEX,NODE,F3,
     *                LPSET1,LPSET2,LPSET3,COVER1,COVER2,COVER3,
     *                NDOM,MBPDOM,NPSND,NPRCV,
     *                LPSND,NPTSND,LPRCV,NPTRCV,IPSET,IPSRC,
     *                WRK01,WRK02,RX,RY,IUT0,IERR)
          IF(IERR.NE.0) THEN
              WRITE(IUT0,*)'ERROR CODE REPORTED FROM OVRST1'
              WRITE(IUT0,*)ERMSGC
              RETURN
          ENDIF
      ENDIF
C
      DO 2300 IB=1,NPINLT
          F3(LPINLT(IB)) = F3INLT
 2300 CONTINUE   

      DO 2400 IB = 1 , NPFIX
            IP=LPFIX(IB)
            RHS(IP) = F3(IP)
 2400 CONTINUE

C
CCYY [8] SOLVE EQUATION
C
      IF(JUNROL.EQ.1)
     *CALL CRSCVA_OLD(NP,NPPMAX,NCRS,NCRS2,NPP,ACRS,TACRS)

      IF(ISOLT.EQ.1) THEN
          CALL BCGSTX(
     *         NPP,NCRS,IPCRS,ACRS,
     *         RHS,F3,EPS,EPSRE,
     *         NMAX,RES,NITR,NODE,NE,NEX,NP,ME,N2,
     *         IPART,LDOM,NBPDOM,NDOM,
     *         IPSLF,IPSND,MBPDOM,NUMIP,
     *         RX,RY,WRK01,WRK02,WRK03,WRK04,WRK05,WRK06,WRK07,
     *         JUNROL,NPPMAX,NCRS2,TS,TACRS,ITPCRS,
     *         IUT0,IERR)
   
!      ELSE IF(ISOLT.EQ.3) THEN
!          CALL IDRBCG(ME,N,NE,NP,NS,NL,NMAX,EPS,RES,RESR,NITR,
!     *                NCRS,NPP,ACRS,IPCRS,RHS,F3,NUMIP,
!     *                IPART,LDOM,NBPDOM,NDOM,IPSLF,IPSND,MBPDOM,
!     *                JUNROL,NPPMAX,NCRS2,TS,TACRS,ITPCRS,
!     *                IUT0,IUT6,IERR)
      ELSE
              WRITE(IUT0,*) 'INVALID VALUE FOR ISOLT'  ,ISOLT
              IERR=1
              RETURN 
      ENDIF
C
      IF(IERR.NE.0) THEN
          WRITE(IUT0,*)'ERROR CODE REPORTED FROM BCGSTX'
          WRITE(IUT0,*)ERMSGC
          RETURN
      ENDIF
C
C
CCCCC SOLUTION FOR F2 CCCCCCCCCCCCCCCCCCCCC
CCYY [2] CAL. TIME, ADV., AND DIFF. TERM 
      CALL ADVDFL_OLD
     * (MCOLOR,MCPART,NCOLOR,NCPART,LLOOP,
     *  N1,N2,NE,NP,MELM,NEX,NODE,
     *  UG,VG,WG,DT,SCT,VISC,
     *  CGAS,CLQD,P,SIGMA,SN,
     *  CEB,CUPWD,CVISL,ICAVI,
     *  E,EX,EY,EZ,EXX,EYY,EZZ,EXY,EYZ,EXZ,
     *  A,F2,RHS,A0,
     *  DELTA,IERR)
      IDUM = 2
      CALL DDCOMX(IPART,IDUM,LDOM,NBPDOM,NDOM,IPSLF,IPSND,MBPDOM,
     *            RHS,A0,RHS,NP,IUT0,IERR,RX,RY,MAXBUF)
      IF(IERR.NE.0) THEN
          WRITE(IUT0,*)
          WRITE(IUT0,*) ERMSGC
          RETURN
      ENDIF
C
C
C
CCYY [3] ADD SOURCE TERM
C
C
      DO 2500 IP = 1,NP
          RHS(IP)=RHS(IP) + DT*F2Y(IP)/CM(IP)
 2500 CONTINUE
C
C
CCYY [4] MATIRIX CONVET FROM ELEMENT-WIZE TO CRS
C
      CALL E2PMAT(MCOLOR,MCPART,NCOLOR,NCPART,LLOOP,
     *            N2,N1,NE,NEX,NCRS,A,ACRS,LTAB,IUT0,IERR)
      IF(IERR.NE.0) THEN
          WRITE(IUT0,*)'ERROR CODE REPORTED FROM E2PMAT'
          WRITE(IUT0,*)ERMSGC
          RETURN
      ENDIF
C
CCYY [5] DIAGONAL SCALING
C
      CALL DGNSCL(ACRS,A0,NP,NE,NCRS,IPCRS,NPP,ME)
C
      DO 2600 IP=1, NP
          RHS(IP) = RHS(IP)/A0(IP)
 2600 CONTINUE
C
CCYY [6] CLEAR CRS MATRIX FOR DIRICHLET B.C.
C
      CALL CLRCRS(IPART,ACRS,NP,NCRS,IPCRS,NPP,
     *            A0,LFIX3D,NUMIP,WRK01)
C
CCYY [7] SET B.C. (1)INLET, (2)OVERSET
C
      IF (JSET.GE.1) THEN
          CALL OVRST1(IPART,NPSET,N1,ME,NE,NP,NEX,NODE,F2,
     *                LPSET1,LPSET2,LPSET3,COVER1,COVER2,COVER3,
     *                NDOM,MBPDOM,NPSND,NPRCV,
     *                LPSND,NPTSND,LPRCV,NPTRCV,IPSET,IPSRC,
     *                WRK01,WRK02,RX,RY,IUT0,IERR)
          IF(IERR.NE.0) THEN
              WRITE(IUT0,*)'ERROR CODE REPORTED FROM OVRST1'
              WRITE(IUT0,*)ERMSGC
              RETURN
          ENDIF
      ENDIF
C
      DO 2700 IB=1,NPINLT
          F2(LPINLT(IB)) = F2INLT
 2700 CONTINUE   

      DO 2800 IB = 1 , NPFIX
            IP=LPFIX(IB)
            RHS(IP) = F2(IP)
 2800 CONTINUE

C
CCYY [8] SOLVE EQUATION
C
      IF(JUNROL.EQ.1)
     *CALL CRSCVA_OLD(NP,NPPMAX,NCRS,NCRS2,NPP,ACRS,TACRS)

      IF(ISOLT.EQ.1) THEN
          CALL BCGSTX(
     *         NPP,NCRS,IPCRS,ACRS,
     *         RHS,F2,EPS,EPSRE,
     *         NMAX,RES,NITR,NODE,NE,NEX,NP,ME,N2,
     *         IPART,LDOM,NBPDOM,NDOM,
     *         IPSLF,IPSND,MBPDOM,NUMIP,
     *         RX,RY,WRK01,WRK02,WRK03,WRK04,WRK05,WRK06,WRK07,
     *         JUNROL,NPPMAX,NCRS2,TS,TACRS,ITPCRS,
     *         IUT0,IERR)
   
!      ELSE IF(ISOLT.EQ.3) THEN
!          CALL IDRBCG(ME,N,NE,NP,NS,NL,NMAX,EPS,RES,RESR,NITR,
!     *                NCRS,NPP,ACRS,IPCRS,RHS,F2,NUMIP,
!     *                IPART,LDOM,NBPDOM,NDOM,IPSLF,IPSND,MBPDOM,
