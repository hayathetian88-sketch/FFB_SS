     *         JUNROL,NPPMAX,NCRS2,TS,TACRS,ITPCRS,
     *         IUT0,IERR)
   
!      ELSE IF(ISOLT.EQ.3) THEN
!          CALL IDRBCG(ME,N,NE,NP,NS,NL,NMAX,EPS,RES,RESR,NITR,
!     *                NCRS,NPP,ACRS,IPCRS,RHS,F1,NUMIP,
!     *                IPART,LDOM,NBPDOM,NDOM,IPSLF,IPSND,MBPDOM,
!     *                JUNROL,NPPMAX,NCRS2,TS,TACRS,ITPCRS,
