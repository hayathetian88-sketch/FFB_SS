C
CCCCC SOLUTION FOR F0 CCCCCCCCCCCCCCCCCCCCC
CCYY [2] CAL. TIME, ADV., AND DIFF. TERM 
      CALL ADVDFL_OLD
     * (MCOLOR,MCPART,NCOLOR,NCPART,LLOOP,
     *  N1,N2,NE,NP,MELM,NEX,NODE,
     *  UG,VG,WG,DT,SCT,VISC,
     *  CGAS,CLQD,P,SIGMA,SN,
     *  CEB,CUPWD,CVISL,ICAVI,
     *  E,EX,EY,EZ,EXX,EYY,EZZ,EXY,EYZ,EXZ,
     *  A,F0,RHS,A0,
     *  DELTA,IERR)
      IDUM = 2
      CALL DDCOMX(IPART,IDUM,LDOM,NBPDOM,NDOM,IPSLF,IPSND,MBPDOM,
     *            RHS,A0,RHS,NP,IUT0,IERR,RX,RY,MAXBUF)
      IF(IERR.NE.0) THEN
          WRITE(IUT0,*)
          WRITE(IUT0,*) ERMSGC
          RETURN
      ENDIF
