      SUBROUTINE DDCOMXI(IPART,LDOM,NBPDOM,NDOM,
     *                   IPSLF,IPSND,MBPDOM,
     *                   IUT0,IERR,
     *                   IBUFSND,IBUFRCV,MAXBUF)
      IMPLICIT NONE
      INTEGER(4) :: IPART,NDOM,MBPDOM
      INTEGER(4) :: LDOM(NDOM),NBPDOM(NDOM)
      INTEGER(4) :: IPSLF(MBPDOM,NDOM),IPSND(MBPDOM,NDOM)
      INTEGER(4) :: MAXBUF,IBUFSND(MAXBUF),IBUFRCV(MAXBUF)
C
      INCLUDE 'mpif.h'
C
      INTEGER(4),PARAMETER :: MAXDOM = 3000
      INTEGER*4 MSGIDS(MAXDOM),MSGSTS(MPI_STATUS_SIZE,MAXDOM)
C
C     TMP Variable
C
      INTEGER(4) :: NSTART,NSTART2,IDOM,IBP,IDIM,ITMP
      INTEGER(4) :: MSGTYP,ISEND,IRECV,MSGLEN,NSKIP,IP,IPS
      INTEGER(4) :: IERR,IUT0
C
C
      CHARACTER*60 ERMSGB
     & / ' ## SUBROUTINE DDCOMXI: FATAL    ERROR OCCURRENCE; RETURNED' /
      CHARACTER*60 EREXP1
     & / ' DIMENSION SIZE OF INTERNAL      ARRAYS IS NOT SUFFICIENT  ' /
      CHARACTER*60 EREXP2
     & / ' DIMENSION SIZE OF PASSED BUFFER ARRAYS IS NOT SUFFICIENT  ' /
      CHARACTER*60 EREXP3
     & / ' RECEIVED NODE NUMBER IS OUT OF THE GLOBAL NODE NUMBER     ' /
C
      IERR = 0
      NSKIP = 1
      IDIM = 0
C
C
C CHECK THE INTERNAL ARRAY SIZE
C
C
      IF(2*NDOM.GT.MAXDOM) THEN
          WRITE(IUT0,*) ERMSGB
          WRITE(IUT0,*) EREXP1
          IERR = 1
          RETURN
      ENDIF
C
C
C POST ALL THE EXPECTED RECEIVES
C
C
      NSTART = 1
      DO 110 IDOM = 1 , NDOM
          MSGTYP = 1
          IRECV  = LDOM(IDOM)-1
          MSGLEN = NSKIP*NBPDOM(IDOM)
C
          IF(NSTART+MSGLEN-1.GT.MAXBUF) THEN
              WRITE(IUT0,*) ERMSGB
              WRITE(IUT0,*) EREXP2
              IERR = 1
              RETURN
          ENDIF
C
          CALL MPI_IRECV(IBUFRCV(NSTART),MSGLEN,MPI_INTEGER,
     &                   IRECV,MSGTYP,
     &                   MPI_COMM_WORLD,MSGIDS(IDOM),IERR)
C
          NSTART = NSTART+MSGLEN
  110 CONTINUE
C
C
C SET UP THE SEND BUFFER
C
C

!CDIR PARALLEL DO PRIVATE(NSTART,IP,IPS)
      DO 210 IDOM = 1 , NDOM
          NSTART  = 0
          DO 205 ITMP = 2 , IDOM
             NSTART = NSTART + NBPDOM(ITMP-1)*NSKIP
 205      CONTINUE
!CDIR NOINNER
!ocl norecurrence(IBUFSND)
          DO IBP=1,NBPDOM(IDOM)
              NSTART2 = NSTART + NSKIP * (IBP-1)
              IP      = IPSLF(IBP,IDOM)
              IPS     = IPSND(IBP,IDOM)
              IBUFSND(NSTART2+1) = IPS
          ENDDO
 210  CONTINUE
      
C
C
C SEND THE RESIDUALS
C
C
      NSTART = 1
      DO 220 IDOM = 1 , NDOM
          MSGTYP = 1
          ISEND  = LDOM(IDOM)-1
          MSGLEN = NSKIP*NBPDOM(IDOM)

          CALL MPI_ISEND(IBUFSND(NSTART),MSGLEN,MPI_INTEGER,
     &                   ISEND,MSGTYP,
     &                   MPI_COMM_WORLD,MSGIDS(NDOM+IDOM),IERR)
          NSTART = NSTART+MSGLEN 
  220 CONTINUE
C
C
C WAIT FOR THE COMPLETION OF ALL THE REQUESTED COMMUNICATIONS
C
C
      CALL MPI_WAITALL(2*NDOM,MSGIDS,MSGSTS,IERR)
C
C SUPERIMPOSE THE RECEIVED RESIDUALS
C
C
      NSTART = 0
      DO IDOM = 1 , NDOM
          DO IBP = 1, NBPDOM(IDOM)
             NSTART2 = NSTART + NSKIP * (IBP-1)
             IPSND(IBP,IDOM)=IBUFRCV(NSTART2+1)+0.1
          ENDDO
          NSTART = NSTART + NSKIP * NBPDOM(IDOM)
      ENDDO
      IF(IERR .eq. 1) THEN
        WRITE(IUT0,*) ERMSGB
        WRITE(IUT0,*) EREXP3
        RETURN
      ENDIF
      RETURN
      END SUBROUTINE DDCOMXI

